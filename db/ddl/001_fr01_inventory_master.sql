--------------------------------------------------------------------------------
-- INVENTORY_BALANCE (item x location x lot)
--------------------------------------------------------------------------------
create table inventory_balance (
    inventory_balance_id number generated by default on null as identity
                          constraint inventory_balance_pk primary key,
    item_id              number not null,
    location_id          number not null,
    lot_id               number,
    -- Oracle unique constraints treat NULL as distinct values, which would allow
    -- duplicate (item_id, location_id) rows for non-lot-tracked items (lot_id null).
    -- lot_id_key collapses NULL to 0 so the uniqueness rule below actually holds.
    lot_id_key           number generated always as (nvl(lot_id, 0)) virtual,
    qty_on_hand          number(14,2) default 0 not null,
    qty_allocated        number(14,2) default 0 not null,
    qty_available         number(14,2) generated always as (qty_on_hand - qty_allocated) virtual,
    last_counted_date     date,
    updated_on            date default sysdate not null,
    constraint invbal_item_loc_lot_uk unique (item_id, location_id, lot_id_key),
    constraint invbal_item_fk foreign key (item_id) references item (item_id),
    constraint invbal_location_fk foreign key (location_id) references location (location_id),
    constraint invbal_lot_fk foreign key (lot_id) references lot (lot_id),
    constraint invbal_onhand_ck check (qty_on_hand >= 0),
    constraint invbal_allocated_ck check (qty_allocated >= 0),
    constraint invbal_alloc_le_onhand_ck check (qty_allocated <= qty_on_hand)
);
comment on table inventory_balance is 'FR-01/FR-06: ton kho hien tai theo item+vi tri+lo, cap nhat real-time';

create index invbal_location_idx on inventory_balance (location_id);
create index invbal_lot_idx on inventory_balance (lot_id);

--------------------------------------------------------------------------------
-- Reporting view: real-time inventory (FR-06 preview, uses FR-01 tables)
--------------------------------------------------------------------------------
create or replace view v_inventory_current as
select
    ib.inventory_balance_id,
    i.item_id,
    i.item_code,
    i.item_name,
    i.device_category,
    w.warehouse_id,
    w.warehouse_code,
    l.location_id,
    l.location_code,
    l.location_type,
    lt.lot_id,
    lt.lot_number,
    lt.qc_status,
    ib.qty_on_hand,
    ib.qty_allocated,
    ib.qty_available,
    ib.last_counted_date,
    ib.updated_on
from inventory_balance ib
join item i     on i.item_id = ib.item_id
join location l on l.location_id = ib.location_id
join warehouse w on w.warehouse_id = l.warehouse_id
left join lot lt on lt.lot_id = ib.lot_id;
comment on table v_inventory_current is 'FR-06: view ton kho real-time theo item/vi tri/lo, dung cho dashboard va IG';
