-- FR-01: Co so du lieu tap trung ve hang ton kho (item, vi tri, lo/batch)
-- Scope: SUPPLIER, WAREHOUSE, LOCATION, ITEM, LOT, INVENTORY_BALANCE
-- Target schema: ADMIN (parsing schema of APEX app 105 / 26house)
-- Note: constraint names are schema-wide unique in Oracle; this schema already
-- has a legacy STOCK_* object set, so new constraint names avoid its prefixes
-- (e.g. LOT_* -> LOTM_*) instead of colliding with it.

set define off

--------------------------------------------------------------------------------
-- SUPPLIER
--------------------------------------------------------------------------------
create table supplier (
    supplier_id      number generated by default on null as identity
                      constraint supplier_pk primary key,
    supplier_code    varchar2(20)  not null,
    supplier_name    varchar2(150) not null,
    contact_name     varchar2(100),
    contact_email    varchar2(120),
    contact_phone    varchar2(30),
    integration_ref  varchar2(60),
    is_active        char(1) default 'Y' not null,
    created_by       varchar2(60) default coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
    created_on       date default sysdate not null,
    updated_by       varchar2(60),
    updated_on       date,
    constraint supplier_code_uk unique (supplier_code),
    constraint supplier_active_ck check (is_active in ('Y','N'))
);
